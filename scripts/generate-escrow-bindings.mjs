import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contractRoot = path.join(repositoryRoot, "contracts/escrow");
const abi = JSON.parse(execFileSync("forge", ["inspect", "src/TaskEscrow.sol:TaskEscrow", "abi", "--json"], {
  cwd: contractRoot,
  encoding: "utf8",
}));

assertInterface(abi);
const canonicalABI = `${JSON.stringify(abi, null, 2)}\n`;
const outputs = new Map([
  [path.join(repositoryRoot, "apps/web/src/app/generated/task-escrow.ts"), typescriptBinding(canonicalABI)],
  [path.join(repositoryRoot, "services/engine/internal/chain/taskescrowabi/generated.go"), goBinding(canonicalABI)],
]);

if (process.argv.includes("--check")) {
  const drift = [];
  for (const [target, expected] of outputs) {
    let actual = "";
    try { actual = readFileSync(target, "utf8"); } catch {}
    if (actual !== expected) drift.push(path.relative(repositoryRoot, target));
  }
  if (drift.length) {
    process.stderr.write(`Escrow ABI bindings are stale: ${drift.join(", ")}\nRun: pnpm abi:generate\n`);
    process.exit(1);
  }
  process.stdout.write("Escrow ABI bindings match the Solidity ABI.\n");
} else {
  for (const [target, content] of outputs) writeFileSync(target, content);
  process.stdout.write(`Generated ${outputs.size} Escrow ABI bindings.\n`);
}

function assertInterface(value) {
  const functions = new Map(value.filter((item) => item.type === "function").map((item) => [item.name, item]));
  const events = new Set(value.filter((item) => item.type === "event").map((item) => item.name));
  const expectedInputs = {
    createTask: ["bytes32", "bytes32", "uint64", "uint256"],
    advanceWorkNonce: ["bytes32", "uint256"],
    selectAgent: ["tuple", "bytes"],
  };
  for (const [name, types] of Object.entries(expectedInputs)) {
    const found = functions.get(name)?.inputs?.map((input) => input.type);
    if (JSON.stringify(found) !== JSON.stringify(types)) throw new Error(`Unexpected ${name} ABI: ${JSON.stringify(found)}`);
  }
  for (const name of ["TaskCreated", "SelectionConfirmed", "WorkNonceAdvanced", "EarningsAccrued", "EarningsWithdrawn", "YieldEligibilityChanged"]) {
    if (!events.has(name)) throw new Error(`Missing required TaskEscrow event ${name}`);
  }
}

function typescriptBinding(json) {
  return `/* Code generated by scripts/generate-escrow-bindings.mjs; DO NOT EDIT. */\n` +
    `export const taskEscrowAbi = ${json.trim()} as const;\n`;
}

function goBinding(json) {
  const escaped = json.trim();
  return `// Code generated by scripts/generate-escrow-bindings.mjs; DO NOT EDIT.\n` +
`package taskescrowabi\n\n` +
`import (\n` +
`\t"encoding/hex"\n` +
`\t"math/big"\n` +
`\t"strings"\n\n` +
`\t"github.com/ethereum/go-ethereum/accounts/abi"\n` +
`\t"github.com/ethereum/go-ethereum/common"\n` +
`)\n\n` +
`const JSON = \`${escaped}\`\n\n` +
`var Contract = mustParse()\n\n` +
`func mustParse() abi.ABI {\n` +
`\tparsed, err := abi.JSON(strings.NewReader(JSON))\n` +
`\tif err != nil { panic(err) }\n` +
`\treturn parsed\n` +
`}\n\n` +
`func MethodID(name string) string {\n` +
`\tmethod, ok := Contract.Methods[name]\n` +
`\tif !ok { panic("TaskEscrow ABI method missing: " + name) }\n` +
`\treturn "0x" + hex.EncodeToString(method.ID)\n` +
`}\n\n` +
`func EventID(name string) string {\n` +
`\tevent, ok := Contract.Events[name]\n` +
`\tif !ok { panic("TaskEscrow ABI event missing: " + name) }\n` +
`\treturn strings.ToLower(event.ID.Hex())\n` +
`}\n\n` +
`func Pack(name string, arguments ...any) ([]byte, error) { return Contract.Pack(name, arguments...) }\n\n` +
`func PackAdvanceWorkNonce(taskID common.Hash, expectedCurrentNonce *big.Int) ([]byte, error) {\n` +
`\treturn Contract.Pack("advanceWorkNonce", taskID, expectedCurrentNonce)\n` +
`}\n`;
}
